// Writes docs/e2e-scenarios.md from tests/e2e/scenarios/index.mjs so the list of test cases cannot drift from the
// code. Usage: node scripts/e2e-scenarios.mjs [--write]  (without --write it fails when the file is stale).
import { readFileSync, writeFileSync } from 'node:fs';
import { scenarios } from '../tests/e2e/scenarios/index.mjs';

const stub = new Proxy({}, { get: () => new Proxy({}, { get: () => () => {} }) });
const list = scenarios({ T: {}, S: stub });
const ids = new Set();
for (const s of list) { if (ids.has(s.id)) throw new Error('duplicate scenario id ' + s.id); ids.add(s.id); if (!s.covers || !s.title || !s.area) throw new Error(s.id + ' needs area, title and covers'); }
const md = ['# E2E scenarios', '', 'Generated by `node scripts/e2e-scenarios.mjs --write` from `tests/e2e/scenarios/index.mjs`. See [e2e.md](e2e.md) for how steps, suites and scenarios fit together.', '',
  `${list.length} scenarios.`, '', '| ID | Area | Scenario | Proves |', '|---|---|---|---|', ...list.map(s => `| ${s.id} | ${s.area} | ${s.title} | ${s.covers} |`), ''].join('\n');
const path = new URL('../docs/e2e-scenarios.md', import.meta.url);
if (process.argv.includes('--write')) writeFileSync(path, md);
else if (readFileSync(path, 'utf8') !== md) { console.error('docs/e2e-scenarios.md is stale: run node scripts/e2e-scenarios.mjs --write'); process.exit(1); }
console.log(`${list.length} scenarios in ${new Set(list.map(s => s.area)).size} areas`);
