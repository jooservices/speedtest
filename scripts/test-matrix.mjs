// Maps every operation of docs/openapi.yaml to the tests that exercise it and fails when one has none.
// A test exercises an operation when its source contains the path (template parameters match any
// segment). Usage: node scripts/test-matrix.mjs [--write]   (--write regenerates docs/test-matrix.md)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import YAML from 'yaml';

const root = new URL('..', import.meta.url).pathname;
const spec = YAML.parse(readFileSync(join(root, 'docs/openapi.yaml'), 'utf8'));
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
const ops = Object.entries(spec.paths).flatMap(([path, item]) => METHODS.filter(m => item[m]).map(m => ({ method: m.toUpperCase(), path, id: item[m].operationId })));

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (['node_modules', '.git', '.tmp', 'vendor'].includes(name)) continue;
    const full = join(dir, name), st = statSync(full);
    if (st.isDirectory()) walk(full, out);
    else if (/_test\.go$/.test(name) || /^tests\/.*\.(mjs|sql)$/.test(relative(root, full))) out.push(full);
  }
  return out;
}
const files = walk(root).map(f => [relative(root, f), readFileSync(f, 'utf8')]);
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const rows = ops.map(op => {
  // A parameter is a literal segment, a template placeholder, or a string concatenation such as "/api/x/"+id+"/ack".
  const param = '(?:[^"\'`\\s/?]+|["\'`]\\s*\\+\\s*[\\w.\\[\\]()]+\\s*\\+?\\s*["\'`]?)';
  const rx = new RegExp(esc(op.path).replace(/\\\{[^}]+\\\}/g, param) + '(?![A-Za-z/_-])');
  const hits = files.filter(([, text]) => rx.test(text)).map(([f]) => f);
  return { ...op, hits };
});

const missing = rows.filter(r => r.hits.length === 0);
const md = ['# API test matrix', '', 'Generated by `node scripts/test-matrix.mjs --write`; `make ci` fails when an operation has no test.', '',
  `Operations: ${rows.length}. Without a test: ${missing.length}.`, '', '| Operation | Method | Path | Tests |', '|---|---|---|---|',
  ...rows.map(r => `| ${r.id} | ${r.method} | \`${r.path}\` | ${r.hits.length ? r.hits.slice(0, 4).map(h => `\`${h}\``).join('<br>') + (r.hits.length > 4 ? `<br>+${r.hits.length - 4} more` : '') : '**none**'} |`), ''].join('\n');
if (process.argv.includes('--write')) writeFileSync(join(root, 'docs/test-matrix.md'), md);
else if (readFileSync(join(root, 'docs/test-matrix.md'), 'utf8') !== md) { console.error('docs/test-matrix.md is stale: run node scripts/test-matrix.mjs --write'); process.exit(1); }
console.log(`operations ${rows.length}, without a test ${missing.length}`);
for (const m of missing) console.log(`  MISSING ${m.method} ${m.path} (${m.id})`);
process.exit(missing.length ? 1 : 0);
